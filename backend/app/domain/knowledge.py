_WORD = re.compile(r"[а-яёa-z0-9]+", re.IGNORECASE)


def _stems(text: str) -> set[str]:
    return {w.lower()[:5] for w in _WORD.findall(text) if len(w) > 2}


def search(question: str, k: int = 3) -> list[dict]:
    q = _stems(question)
    scored = []
    for e in KB:
        keys = _stems(e["keys"])
        title = _stems(e["title"])
        body = _stems(e["text"])
        s = 3 * len(q & keys) + 2 * len(q & title) + 0.5 * len(q & body)
        if s > 0:
            scored.append((s, e))
    scored.sort(key=lambda x: -x[0])
    return [e for _, e in scored[:k]]
